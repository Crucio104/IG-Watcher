import SwiftUI

/// Lingue supportate dall'applicazione
public enum AppLanguage: String, CaseIterable, Identifiable, Codable {
    case english = "en"
    case spanish = "es"
    case french = "fr"
    case german = "de"
    case italian = "it"
    case portuguese = "pt"
    case japanese = "ja"
    case chinese = "zh"

    public var id: String { rawValue }

    public var displayName: String {
        switch self {
        case .english: return "English"
        case .spanish: return "Español"
        case .french: return "Français"
        case .german: return "Deutsch"
        case .italian: return "Italiano"
        case .portuguese: return "Português"
        case .japanese: return "Japanese"
        case .chinese: return "Chinese"
        }
    }
}

/// Gestore centrale della lingua e delle stringhe tradotte
@MainActor
public final class LocalizationManager: ObservableObject {
    public static let shared = LocalizationManager()

    private let languageKey = "com.instagramwatcher.selected_language"

    @Published public var currentLanguage: AppLanguage {
        didSet {
            UserDefaults.standard.set(currentLanguage.rawValue, forKey: languageKey)
        }
    }

    private init() {
        if let saved = UserDefaults.standard.string(forKey: languageKey),
           let lang = AppLanguage(rawValue: saved) {
            self.currentLanguage = lang
        } else {
            // Default: Inglese come richiesto
            self.currentLanguage = .english
        }
    }

    public func setLanguage(_ language: AppLanguage) {
        self.currentLanguage = language
    }

    public func tr(_ key: String) -> String {
        return strings[currentLanguage]?[key] ?? strings[.english]?[key] ?? key
    }

